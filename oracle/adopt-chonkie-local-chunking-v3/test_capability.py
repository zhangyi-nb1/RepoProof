@pytest.mark.parametrize("strategy", STRATEGIES)
def test_upstream_errors_wrapped(strategy: str) -> None:
    with pytest.raises(ConsumerChunkingError):
        chunk_documents(
            {
                "documents": [{"document_id": "doc-bad", "text": None, "metadata": {}}],
                "strategy": strategy,
                "chunk_size": CHUNK_SIZE,
            }
        )


def test_strategies_differ_on_run_on_document() -> None:
    """The strategy-sensitive fixture: sentence keeps the indivisible
    run-on whole (R2), recursive splits it — the adapter must reflect
    the requested strategy, not silently reuse one chunker."""
    sent = _records_by_doc(chunk_documents(_request(PUBLIC, "sentence")))["doc-104-run-on-zh"]
    rec = _records_by_doc(chunk_documents(_request(PUBLIC, "recursive")))["doc-104-run-on-zh"]
    assert [(r["char_start"], r["char_end"]) for r in sent] != [(r["char_start"], r["char_end"]) for r in rec]
    assert len(sent) == 1 and sent[0]["units"] > CHUNK_SIZE  # R2 in action
    assert len(rec) >= 2 and all(r["units"] <= CHUNK_SIZE for r in rec)
